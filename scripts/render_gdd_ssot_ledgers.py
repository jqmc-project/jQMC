def _case_expansion(dimensions: dict[str, Any]) -> list[dict[str, Any]]:
    keys = list(dimensions)
    choices = [value if isinstance(value, list) else [value] for value in dimensions.values()]
    return [dict(zip(keys, values, strict=True)) for values in product(*choices)]


def _select_case_binding(value: Any, selector: dict[str, Any]) -> Any:
    """Resolve selector-indexed maps so one rendered block means one concrete case."""
    if isinstance(value, list):
        if value and all(isinstance(item, dict) and "when" in item for item in value):
            matches = [
                item for item in value if all(selector.get(key) == expected for key, expected in item.get("when", {}).items())
            ]
            if len(matches) == 1:
                return _select_case_binding({key: item for key, item in matches[0].items() if key != "when"}, selector)
        return [_select_case_binding(item, selector) for item in value]
    if not isinstance(value, dict):
        return value
    selected: dict[str, Any] = {}
    for key, child in value.items():
        if key == "cases" and isinstance(child, list):
            resolved_cases = _select_case_binding(child, selector)
            if isinstance(resolved_cases, dict):
                selected.update(resolved_cases)
                continue
        if "_by_" in key and isinstance(child, dict):
            base, axis = key.rsplit("_by_", 1)
            if axis in selector and selector[axis] in child:
                selected[base] = _select_case_binding(child[selector[axis]], selector)
                continue
        if key in selector and isinstance(child, list) and selector[key] in child:
            selected[key] = _select_case_binding(selector[key], selector)
            continue
        selected[key] = _select_case_binding(child, selector)
    return selected


