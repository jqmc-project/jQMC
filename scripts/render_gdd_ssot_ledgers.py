def _ledger_name(relative: Path) -> str:
    """Mirror the SSoT layout: fixtures/ inputs, guarantees/ per-test ledgers."""
    stem = relative.stem.replace("_", "-")
    if relative.parent == Path("."):
        return f"{stem}.md"
    return f"{relative.parent.as_posix()}/{stem}.md"


def _documents() -> list[tuple[Path, dict[str, Any]]]:
    documents = []
    for path in sorted(SSOT_ROOT.rglob("*.yaml")):
        relative = path.relative_to(SSOT_ROOT)
        if relative.parts[0] == "schemas":
            continue
        if relative.parts[0] == "guarantees" and len(relative.parts) > 2:
            continue  # one split guarantee file; load_ledger assembles it into its module (issue 205)
        if relative.parts and relative.parts[0] == "guarantees":
            documents.append((relative, load_ledger(path)))
        else:
            documents.append((relative, yaml.safe_load(path.read_text(encoding="utf-8"))))
    return documents


def _governance_map(documents: list[tuple[Path, dict[str, Any]]]) -> list[list[Any]]:
    """One row per guarantee ledger: lifecycle, owned modules, symbol counts."""
    ownership = next(document for relative, document in documents if relative.as_posix() == "symbol_ownership.yaml")[
        "ownership"
    ]
    live = discover_python_ownership(ROOT)
    modules_by_ledger: dict[str, list[str]] = {}
    symbols_by_ledger: dict[str, list[int]] = {}
    for module, entry in ownership.items():
        ledger = entry["ledger"]
        modules_by_ledger.setdefault(ledger, []).append(module)
        discovered = live[module]
        public = sum(len(discovered["public_symbols"][kind]) for kind in discovered["public_symbols"])
        private = sum(len(discovered["private_symbols"][kind]) for kind in discovered["private_symbols"])
        totals = symbols_by_ledger.setdefault(ledger, [0, 0])
        totals[0] += public
        totals[1] += private
    rows: list[list[Any]] = []
    for relative, document in documents:
        if relative.parent.name != "guarantees":
            continue
        lifecycle = document.get("document", {}).get("lifecycle")
        ledger_path = f"gdd/ssot/{relative.as_posix()}"
        modules = modules_by_ledger.get(ledger_path, [])
        public, private = symbols_by_ledger.get(ledger_path, (0, 0))
        if lifecycle == "placeholder":
            ledger_cell = f"`{relative.name}`"
        else:
            ledger_cell = f"[`{relative.name}`]({_ledger_name(relative)})"
        rows.append(
            [
                ledger_cell,
                lifecycle,
                len(document.get("guarantees") or []),
                len(modules) if len(modules) != 1 else modules[0],
                public,
                private,
            ]
        )
    rows.sort(key=lambda row: (row[1] != "pre-cutover", str(row[0])))
    return rows


#: Module ledgers always rendered as an index plus one dossier page per guarantee.
ALWAYS_SPLIT_LEDGERS = frozenset({"guarantees/jqmc_rs.yaml"})

#: Any other module ledger rendered by ``_render_module_ledger_human`` whose single-page
#: view exceeds this many UTF-8 bytes is split the same way. GitHub stops rendering a
#: Markdown blob at 1 MiB and the self-test gate rejects any page above 900_000 bytes;
#: splitting from 700_000 keeps every single-page ledger at least ~22 % below that gate
#: (jqmc-optimizer.md had reached 908_595 bytes).
SPLIT_LEDGER_THRESHOLD_BYTES = 700_000


def _split_dossier_path(relative: Path, guarantee_id: str) -> str:
    """Output path of one guarantee's dossier page of a split module ledger."""
    name = _ledger_name(relative)
    return f"{Path(name).parent.as_posix()}/{Path(name).stem}/{guarantee_id.lower()}.md"


def _render_split_module_ledger(
    document: dict[str, Any],
    relative: Path,
    *,
    full_page: str | None = None,
) -> dict[str, str]:
    """Render a large module as an index plus one self-contained page per guarantee.

    GitHub does not render arbitrarily large Markdown blobs.  Splitting at the
    guarantee boundary preserves the audit rule that, once a reviewer selects a
    guarantee, every blocking test and its fixture binding can be read from top
    to bottom without leaving that page.
    """
    name = _ledger_name(relative)
    stem = Path(name).stem
    full = full_page if full_page is not None else _render_module_ledger_human(document, f"gdd/ssot/{relative.as_posix()}")
    first_anchor = '<a id="guarantee-'
    index, separator, _details = full.partition(first_anchor)
    if not separator:
        raise ValueError(f"split ledger {relative} has no guarantee anchors")

    index = index.replace(
        "## Guarantees\n\n"
        "Each guarantee links to its tests. Test details keep the concrete pytest case, input file, "
        "wavefunction/component, electron configuration, precision/backend, and verdict together.\n",
        "## Audit dossiers\n\n"
        "Each row opens one self-contained guarantee page. After opening it, read downward: "
        "the requirement, scope, blocking tests, concrete fixture cases, electron configuration, "
        "precision/backend, and verdict remain together.\n",
    )
    index = index.rstrip() + "\n"
    outputs = {name: index}
    for guarantee in document["guarantees"]:
        guarantee_id = guarantee["id"]
        anchor = f"guarantee-{guarantee_id.lower()}"
        child_name = f"{Path(name).parent.as_posix()}/{stem}/{guarantee_id.lower()}.md"
        index_link = f"{stem}/{guarantee_id.lower()}.md#{anchor}"
        outputs[name] = outputs[name].replace(f"](#{anchor})", f"]({index_link})")

        child_document = {**document, "guarantees": [guarantee]}
        child = _render_module_ledger_human(
            child_document,
            f"gdd/ssot/{relative.as_posix()}",
            repository_prefix="../../../../",
        )
        summary_start = child.index("## Guarantees\n")
        dossier_start = child.index(f'<a id="{anchor}"></a>')
        child = child[:summary_start] + child[dossier_start:]
        child_lines = child.splitlines()
        child_lines[0] = f"# Audit dossier: {guarantee.get('name', guarantee_id)}"
        child = "\n".join(child_lines).rstrip() + "\n"
        outputs[child_name] = child
    outputs[name] = outputs[name].rstrip() + "\n"
    return outputs


#: A guarantee dossier page that is still above ``SPLIT_LEDGER_THRESHOLD_BYTES`` after
#: repeated-rule compaction is continued across numbered pages. The first
#: page keeps the dossier path, the guarantee anchor, the requirement, the scope and the
#: complete blocking-evidence table; each continuation page holds whole per-test
#: evidence sections (a test section is never cut) and holds at most this many bytes of
#: sections. A new page must also pass the repository's check-added-large-files hook
#: (500 KB), so the budget stays below that with room for the page navigation.
DOSSIER_PART_BUDGET_BYTES = 450_000

_TEST_SECTION_MARK = '<a id="test-'
_MACHINERY_MARK = "## Machinery (appendix)\n"
_ANCHOR_DEFINITION = __import__("re").compile(r'<a id="([^"]+)"></a>')
_LOCAL_LINK = __import__("re").compile(r"\]\(#([^)\s]+)\)")
_TEST_SECTION_START = __import__("re").compile(r"\n(?=<a id=\"test-)")


def _dossier_part_path(name: str, part: int) -> str:
    """Output path of continuation page ``part`` (2, 3, ...) of the dossier ``name``."""
    return f"{name.removesuffix('.md')}--part-{part:02d}.md"


def _split_dossier_sections(name: str, page: str) -> tuple[str, list[str], str]:
    """Split one dossier page into (front matter, per-test sections, appendix)."""
    guarantee_at = page.find('<a id="guarantee-')
    first_test = page.find(f"\n{_TEST_SECTION_MARK}", guarantee_at)
    if guarantee_at < 0 or first_test < 0:
        raise ValueError(f"dossier {name} has no per-test evidence sections to continue")
    machinery_at = page.rfind(f"\n{_MACHINERY_MARK}")
    if machinery_at < first_test:
        machinery_at = len(page)
    front, body, appendix = page[: first_test + 1], page[first_test + 1 : machinery_at + 1], page[machinery_at + 1 :]
    starts = [0] + [match.start() + 1 for match in _TEST_SECTION_START.finditer(body)]
    sections = [body[start:end] for start, end in zip(starts, [*starts[1:], len(body)], strict=True)]
    return front, sections, appendix


def _continue_dossier(name: str, page: str, budget: int = DOSSIER_PART_BUDGET_BYTES) -> dict[str, str]:
    """Continue one oversized guarantee dossier across numbered pages.

    Whole per-test sections are packed in order onto continuation pages of at most
    ``budget`` bytes. Every in-page link ``](#anchor)`` whose anchor moved to another
    page of the dossier is rewritten to that page, and the pages link to each other.
    No line of the original page is dropped or duplicated except the added navigation.
    """
    front, sections, appendix = _split_dossier_sections(name, page)
    parts: list[list[str]] = [[]]
    used = 0
    for section in sections:
        size = len(section.encode("utf-8"))
        if size > budget:
            raise ValueError(f"{name}: one test section is {size} bytes, above the {budget}-byte page budget")
        if parts[-1] and used + size > budget:
            parts.append([])
            used = 0
        parts[-1].append(section)
        used += size
    leaf = name.rpartition("/")[2]
    title = front.split("\n", 1)[0].removeprefix("# Audit dossier: ").removeprefix("# ")
    guarantee_anchor = _ANCHOR_DEFINITION.search(front[front.find('<a id="guarantee-') :]).group(1)
    names = [_dossier_part_path(name, number) for number in range(2, len(parts) + 2)]
    leaves = [part_name.rpartition("/")[2] for part_name in names]
    total = len(parts) + 1

    def tests_on(part: list[str]) -> str:
        headings = [
            next(line for line in section.split("\n") if line.startswith("### ")).removeprefix("### ") for section in part
        ]
        first, last = headings[0], headings[-1]
        return f"`{first}`" if first == last else f"`{first}` ... `{last}` ({len(part)} tests)"

    contents = [
        f"### Continuation pages\n\nThe per-test evidence sections of this guarantee continue on {len(parts)} "
        "further page(s), in the order of the blocking-evidence table above. Each test section is complete "
        "on one page.\n\n"
        + "".join(
            f"- Page {number + 2} of {total}: [{leaf_name}]({leaf_name}) -- {tests_on(part)}\n"
            for number, (leaf_name, part) in enumerate(zip(leaves, parts, strict=True))
        )
        + "\n"
    ]
    pages = {name: (front + contents[0] + appendix).rstrip("\n") + "\n"}
    for number, (part_name, part) in enumerate(zip(names, parts, strict=True)):
        previous = leaf if number == 0 else leaves[number - 1]
        navigation = (
            f"Page {number + 2} of {total} of the audit dossier [{title}]({leaf}#{guarantee_anchor}). "
            f"Previous page: [{previous}]({previous})."
            + (f" Next page: [{leaves[number + 1]}]({leaves[number + 1]})." if number + 1 < len(parts) else " Last page.")
        )
        pages[part_name] = (
            f"# Audit dossier: {title} (page {number + 2} of {total})\n\n{GENERATED_NOTE}\n\n{navigation}\n\n"
            "## Per-test evidence (continued)\n\n" + "".join(part) + f"\n{navigation}\n"
        )
    owner = {anchor: page_name for page_name, text in pages.items() for anchor in _ANCHOR_DEFINITION.findall(text)}

    def relink(page_name: str, text: str) -> str:
        def _sub(match):
            target = owner.get(match.group(1))
            if target is None or target == page_name:
                return match.group(0)
            return f"]({target.rpartition('/')[2]}#{match.group(1)})"

        return _LOCAL_LINK.sub(_sub, text)

    return {page_name: relink(page_name, text) for page_name, text in pages.items()}


def render_all(*, with_generated_views: bool = False):
    outputs: dict[str, str] = {}
    documents = _documents()
    placeholders: list[str] = []
    index_rows: list[list[Any]] = []
    split_ledgers: set[str] = set()
    dossier_pages: set[str] = set()
    from scripts.gdd_audit_views import INDEPENDENT_MODULE_LEDGERS, independent_module_navigation

    module_aggregates: dict[str, str] = {}
    for relative, document in documents:
        lifecycle = document.get("document", {}).get("lifecycle", document.get("lifecycle"))
        if lifecycle == "placeholder":
            placeholders.append(relative.as_posix())
            continue
        document_id = document.get("document", {}).get("id", document.get("contract_id", ""))
        renderer = RENDERERS.get(document_id)
        if renderer is None and relative.parent.name == "guarantees":
            renderer = _render_module_ledger_human
        if renderer is None:
            raise SystemExit(f"no audit renderer registered for {relative} (id={document_id!r})")
        name = _ledger_name(relative)
        if relative.as_posix() in INDEPENDENT_MODULE_LEDGERS:
            full_page = _render_module_ledger_human(document, f"gdd/ssot/{relative.as_posix()}")
            module_aggregates[name] = full_page.replace("](verdicts.md", f"]({'../' * name.count('/')}verdicts.md")
            rendered_outputs = _render_split_module_ledger(document, relative, full_page=full_page)
            rendered_outputs[name] = independent_module_navigation(relative)
            split_ledgers.add(relative.as_posix())
            dossier_pages.update(set(rendered_outputs) - {name})
        elif relative.as_posix() in ALWAYS_SPLIT_LEDGERS:
            rendered_outputs = _render_split_module_ledger(document, relative)
            split_ledgers.add(relative.as_posix())
            dossier_pages.update(set(rendered_outputs) - {name})
        else:
            single_page = renderer(document, f"gdd/ssot/{relative.as_posix()}")
            if renderer is _render_module_ledger_human and len(single_page.encode("utf-8")) > SPLIT_LEDGER_THRESHOLD_BYTES:
                rendered_outputs = _render_split_module_ledger(document, relative)
                split_ledgers.add(relative.as_posix())
                dossier_pages.update(set(rendered_outputs) - {name})
            else:
                rendered_outputs = {name: single_page}
        for output_name, content in rendered_outputs.items():
            depth = output_name.count("/")
            if depth:
                content = content.replace("](verdicts.md", f"]({'../' * depth}verdicts.md")
            outputs[output_name] = content
        if relative.parent.name == "guarantees":
            continue  # per-module guarantee views are indexed by the coverage map below

        enforcement_map = document.get("enforcement_map", {})
        debt = sum(1 for value in enforcement_map.values() if value == "not-yet-enforced") if enforcement_map else "-"
        index_rows.append([f"[{name}]({name})", QUESTIONS.get(document_id, "-"), debt])

    lines = ["# GDD SSoT ledgers", "", GENERATED_NOTE, ""]
    lines.append("One generated, audit-first view per SSoT contract. The YAML files remain the")
    lines.append("single source of truth; regenerate with `python scripts/render_gdd_ssot_ledgers.py`.")
    lines.append("Per-obligation derivative coverage matrices are embedded in the derivative guarantee dossiers;")
    lines.append("the derivative guarantee summary also lives at `gdd/ssot/guarantees/README.md`.")
    lines.append("")

    index_rows.sort(key=lambda row: "verdicts.md" not in str(row[0]))
    _table(lines, ["ledger", "question it answers", "not-yet-enforced sections"], index_rows)
    lines.append("## Guarantee coverage map (which production module is governed by what)")
    lines.append("")
    lines.append(
        "A placeholder ledger means the module has NO governed guarantees yet: its symbols are "
        "inventoried, but nothing about its behavior is contractually guaranteed. Repository "
        f"cutover requires zero placeholders (currently {len(placeholders)})."
    )
    lines.append("")
    _table(
        lines,
        ["guarantee ledger", "lifecycle", "guarantees", "modules owned", "public symbols", "private symbols"],
        _governance_map(documents),
    )
    outputs["README.md"] = "\n".join(lines).rstrip("\n") + "\n"
    from scripts.gdd_audit_views import HOT_AGGREGATES, isolate_audit_dossiers, full_view_mirror, stable_dossier_source_details

    aggregates = {name: outputs[name] for name in HOT_AGGREGATES}
    aggregates.update(module_aggregates)
    outputs = isolate_audit_dossiers(outputs, documents, _render_module_ledger_human)
    dossier_pages.update(
        name for name in outputs if name.startswith("guarantees/derivatives/") and name != "guarantees/derivatives/context.md"
    )
    registry = _crossref_registry(documents, split_ledgers)
    outputs = _crossref(outputs, registry)
    from scripts.gdd_audit_views import append_authored_derivative_definitions
    from gdd.engine.ledger import authored_document

    authored_derivatives = None
    authored_modules = {}
    for relative, _document in documents:
        if relative.as_posix() == "guarantees/derivatives.yaml":
            authored_derivatives = authored_document(_document, SSOT_ROOT / relative)
            append_authored_derivative_definitions(outputs, authored_derivatives)
        if relative.as_posix() in INDEPENDENT_MODULE_LEDGERS:
            from scripts.gdd_audit_views import append_authored_module_definitions

            authored_modules[relative.as_posix()] = authored_document(_document, SSOT_ROOT / relative)
            append_authored_module_definitions(outputs, authored_modules[relative.as_posix()], relative)
    final: dict[str, str] = {}
    for name, content in outputs.items():
        if len(content.encode("utf-8")) <= SPLIT_LEDGER_THRESHOLD_BYTES:
            final[name] = content
            continue
        compacted = _compact_repeated_rules(content)
        if name not in dossier_pages or len(compacted.encode("utf-8")) <= SPLIT_LEDGER_THRESHOLD_BYTES:
            final[name] = compacted
            continue
        # A single guarantee still too large for one page continues across numbered pages.
        for page_name, page in _continue_dossier(name, content).items():
            dossier_pages.add(page_name)
            if page_name != name and page_name in outputs:
                raise ValueError(f"continuation page {page_name} collides with another generated page")
            if len(page.encode("utf-8")) > SPLIT_LEDGER_THRESHOLD_BYTES:
                page = _compact_repeated_rules(page)
            final[page_name] = page
    # Retain precise current locations before stabilizing only committed dossiers.
    rich_final = dict(final)
    final = {
        name: stable_dossier_source_details(content, name) if name in dossier_pages else content
        for name, content in final.items()
    }
    if with_generated_views:
        from scripts.gdd_audit_views import complete_derivative_aggregate

        aggregate_views = _crossref(aggregates, registry)
        assert authored_derivatives is not None
        aggregate_views["guarantees/derivatives.md"] = complete_derivative_aggregate(
            aggregate_views["guarantees/derivatives.md"], authored_derivatives
        )
        for relative, document in authored_modules.items():
            name = INDEPENDENT_MODULE_LEDGERS[relative]
            aggregate_views[name] = complete_derivative_aggregate(aggregate_views[name], document)
        return final, full_view_mirror({**rich_final, **aggregate_views})
    return final


_RANGE_TOKEN = __import__("re").compile(r"(?<![\w\[`/#-])([BCPR]\d{2})-([BCPR]\d{2})(?![\w-])")
_ID_TOKEN = __import__("re").compile(
    r"(?<![\w\[`/#-])([A-Z][A-Z0-9]+(?:-[A-Za-z0-9_]+)+|WF-(?:SRC|PATTERN)-[A-Z0-9-]+|[BCPR]\d{2})(?![\w-])"
)


def _crossref_registry(
    documents: list[tuple[Path, dict[str, Any]]], split_ledgers: set[str] | frozenset[str] = ALWAYS_SPLIT_LEDGERS
) -> dict[str, str]:
    """Map every project-issued ID to its ledger anchor (path#anchor).

    A guarantee of a split module ledger (``split_ledgers``) links to its own dossier page.
    """
    from scripts.gdd_audit_views import INDEPENDENT_MODULE_LEDGERS

    registry: dict[str, str] = {}
    for relative, document in documents:
        lifecycle = document.get("document", {}).get("lifecycle", document.get("lifecycle"))
        if lifecycle == "placeholder":
            continue
        name = _ledger_name(relative)
        if relative.as_posix() == "verdicts.yaml":
            for row in document.get("verdict_methods", []):
                registry[row["id"]] = f"{name}#{row['id'].lower()}"
            for row in document.get("comparison_policies", []):
                registry[row["id"]] = f"{name}#pass-criteria-comparison-policies"
            for row in document.get("observation_policies", []):
                registry[row["id"]] = f"{name}#pass-criteria-observation-policies"
            tolerance_registry = document.get("tolerance_registry", {})
            for row in tolerance_registry.get("symbol_pairs", []) + tolerance_registry.get("resolvers", []):
                registry[row["id"]] = f"{name}#pass-criteria-tolerance-registry"
        if relative.parent.name == "guarantees":
            for row in document.get("guarantees", []) + document.get("module_evidence", []):
                if relative.as_posix() == "guarantees/derivatives.yaml":
                    registry[row["id"]] = f"guarantees/derivatives/{row['id'].lower()}.md#guarantee-{row['id'].lower()}"
                elif relative.as_posix() in split_ledgers or relative.as_posix() in INDEPENDENT_MODULE_LEDGERS:
                    registry[row["id"]] = f"{_split_dossier_path(relative, row['id'])}#guarantee-{row['id'].lower()}"
                else:
                    registry[row["id"]] = f"{name}#guarantees"
            for fixture in document.get("fixture_sets", []):
                anchor = "finite-difference-sentinels" if "FD" in fixture["id"] else "assurance-chain"
                registry[fixture["id"]] = f"{name}#{anchor}"
            domain = document.get("domain", {})
            for section, letter in (
                ("reviewed_branch_inventory", "B"),
                ("reviewed_validity_inventory", "C"),
                ("reviewed_parameter_leaf_inventory", "P"),
                ("reviewed_numerical_regime_inventory", "R"),
            ):
                ids = domain.get(section, {}).get("source_ids", {})
                for index in range(1, int(ids.get("count", 0)) + 1):
                    registry[f"{letter}{index:02d}"] = "repo:gdd/engine/derivative_inventory.py"
        if relative.as_posix() == "fixtures/sources.yaml":
            for source_id in document.get("sources", {}):
                registry[source_id] = f"{name}#committed-sources"
        if relative.as_posix() == "fixtures/wavefunctions.yaml":
            for case in document.get("canonical_suite", {}).get("cases", []):
                registry[case["id"]] = f"{name}#canonical-cases"
    return registry


def _crossref(outputs: dict[str, str], registry: dict[str, str]) -> dict[str, str]:
    """Turn every plain occurrence of a known ID into a link to its definition."""

    def link_for(identifier: str, current: str) -> str | None:
        target = registry.get(identifier)
        if target is None:
            return None
        if target.startswith("repo:"):
            return "../" * (2 + current.count("/")) + target[len("repo:") :]
        target_file, _, anchor = target.partition("#")
        if target_file == current:
            if identifier in {"CMP", "OBS"}:
                return None
            return f"#{anchor}" if anchor else None
        prefix = "../" * current.count("/")
        return f"{prefix}{target_file}#{anchor}" if anchor else f"{prefix}{target_file}"

    linked: dict[str, str] = {}
    for current, content in outputs.items():
        out_lines = []
        for line in content.split("\n"):
            if line.startswith("#"):
                out_lines.append(line)
                continue

            def _sub(match):
                identifier = match.group(1)
                target = registry.get(identifier)
                if target is None:
                    return identifier
                target_file, _, anchor = target.partition("#")
                # definitional first-column rows and same-file section rows stay plain
                if (
                    not target.startswith("repo:")
                    and target_file == current
                    and line.startswith((f"| {identifier} ", f"### {identifier}"))
                ):
                    return identifier
                href = link_for(identifier, current)
                if href is None:
                    return identifier
                if target_file == current and f"#{identifier.lower()}" != href and line.startswith("| "):
                    pass
                return f"[{identifier}]({href})"

            def _sub_range(match):
                left, right = match.group(1), match.group(2)
                left_href = link_for(left, current)
                right_href = link_for(right, current)
                if left_href is None or right_href is None:
                    return match.group(0)
                return f"[{left}]({left_href})-[{right}]({right_href})"

            line = _RANGE_TOKEN.sub(_sub_range, line)
            out_lines.append(_ID_TOKEN.sub(_sub, line))
        linked[current] = "\n".join(out_lines)
    return linked


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="compatibility alias: refresh ignored display outputs")
    parser.parse_args()
    from scripts.gdd_audit_views import GENERATED_VIEW_ROOT

    outputs, generated_views = render_all(with_generated_views=True)
    generated_root = ROOT / GENERATED_VIEW_ROOT
    generated_root.mkdir(parents=True, exist_ok=True)
    for path in generated_root.rglob("*.md"):
        if path.relative_to(generated_root).as_posix() not in generated_views:
            path.unlink()
    for name, content in generated_views.items():
        target = generated_root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    LEDGER_ROOT.mkdir(parents=True, exist_ok=True)
    for path in LEDGER_ROOT.rglob("*.md"):
        if path.relative_to(LEDGER_ROOT).as_posix() not in outputs:
            path.unlink()
    for directory in sorted(LEDGER_ROOT.rglob("*"), reverse=True):
        if directory.is_dir() and not any(directory.iterdir()):
            directory.rmdir()
    for name, content in outputs.items():
        target = LEDGER_ROOT / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8")
    print(f"wrote {len(outputs)} ledgers under {LEDGER_ROOT.relative_to(ROOT)}")
    return 0


