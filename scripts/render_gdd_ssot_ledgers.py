def _compact_repeated_rules(page: str) -> str:
    """Print each repeated fixed rule once per page; later copies link back to it.

    Used only on pages above ``SPLIT_LEDGER_THRESHOLD_BYTES`` (a single guarantee
    dossier cannot be split further at a guarantee boundary). The first occurrence of
    each rule keeps its full text behind an anchor; every later occurrence names the
    rule and links to that anchor on the same page. No rule, test, case, observation
    or verdict row is dropped, so the page stays self-contained.
    """
    lines = page.split("\n")
    counts: dict[str, int] = {}
    for line in lines:
        if line in _REPEATED_RULES:
            counts[line] = counts.get(line, 0) + 1
    seen: set[str] = set()
    for index, line in enumerate(lines):
        if counts.get(line, 0) < 2:
            continue
        anchor, short_name = _REPEATED_RULES[line]
        if line in seen:
            lines[index] = f"{short_name}: the rule stated in full [earlier on this page](#{anchor}) applies here."
        else:
            seen.add(line)
            lines[index] = f'<a id="{anchor}"></a>{line}'
    return "\n".join(lines)


