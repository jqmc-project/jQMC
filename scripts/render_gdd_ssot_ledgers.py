def _audit_compact(value: Any) -> str:
    """Compact nested bindings without erasing list-vs-mapping structure."""
    if isinstance(value, dict):
        return "{" + ", ".join(f"{key}: {_audit_compact(item)}" for key, item in value.items()) + "}"
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_audit_compact(item) for item in value) + "]"
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


