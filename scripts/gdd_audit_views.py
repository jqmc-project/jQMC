from __future__ import annotations

from copy import deepcopy
import posixpath
import re
from pathlib import Path
from typing import Any, Callable

HOT_AGGREGATES = frozenset({"README.md", "guarantees/derivatives.md"})
# Pairwise merge evidence identifies these two otherwise-small modules as shared hot spots.
INDEPENDENT_MODULE_LEDGERS = {
    "guarantees/_precision.yaml": "guarantees/-precision.md",
    "guarantees/coulomb_potential.yaml": "guarantees/coulomb-potential.md",
}
GENERATED_VIEW_ROOT = Path("gdd/derived/human-ledger")
_NOTE = "<!-- Generated by scripts/render_gdd_ssot_ledgers.py. Do not edit by hand. -->"
_LINK = re.compile(r"(\]\()([^\s)]+)(\))")
_FENCE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")
_SOURCE_LINE_ANCHOR = re.compile(r"(.+\.(?:py|rs))#L[0-9]+(?:-L[0-9]+)?$")
_GENERATED_CALLEE = re.compile(
    r"(\| (?:required per normal call|required in the selected branch|required|conditional or structural); callee `)"
    r"([^`\s]+\.(?:py|rs)):[0-9]+:([^`]+)(`)"
)
_GENERATED_SOURCE_LABEL = re.compile(r"(Test source: \[`)([^`\s]+\.(?:py|rs)):[0-9]+(`\]\()")


def stable_dossier_source_details(content: str, dossier: str) -> str:
    """Keep generated source identities stable, with exact detail in the full mirror.

    Only generated source hrefs, callee/fixture labels and the pre-test symbol
    inventory change. Authored definitions, fenced payloads, comparison rows,
    owner references and non-source anchors retain their original bytes.
    """
    full = posixpath.relpath(GENERATED_VIEW_ROOT.as_posix() + "/" + dossier, posixpath.dirname("gdd/ledger/" + dossier))
    result = []
    fence = None
    authored = False
    before_tests = True
    for line in content.splitlines(keepends=True):
        match = _FENCE.match(line)
        if authored:
            result.append(line)
        elif fence:
            result.append(line)
            if match and match[1][0] == fence[0] and len(match[1]) >= fence[1] and not match[2].strip():
                fence = None
        elif match:
            fence = (match[1][0], len(match[1]))
            result.append(line)
        else:
            if line.startswith("## Authored guarantee definition"):
                authored = True
                result.append(line)
                continue
            if '<a id="test-' in line:
                before_tests = False
            if before_tests and line.startswith("| Tolerance symbols |"):
                ending = "\n" if line.endswith("\n") else ""
                result.append(
                    "| Tolerance symbols | Exact symbols remain in the per-test Comparison rows below; "
                    f"[complete aggregate inventory]({full}). |" + ending
                )
                continue

            def stable_href(link):
                href = link[2]
                source = _SOURCE_LINE_ANCHOR.fullmatch(href)
                if source and not href.startswith(("/", "#")) and ":" not in href.split("/", 1)[0]:
                    return link[1] + source[1] + link[3]
                return link[0]

            line = _LINK.sub(stable_href, line)
            line = _GENERATED_CALLEE.sub(lambda value: value[1] + value[2] + "::" + value[3] + value[4], line)
            line = _GENERATED_SOURCE_LABEL.sub(lambda value: value[1] + value[2] + value[3], line)
            result.append(line)
    return "".join(result)


def relocate_links(content: str, source: str, target: str, *, mirror: bool = False) -> str:
    """Move a page without changing the repository object addressed by its links."""

    def replace(match):
        href = match[2]
        if href.startswith("#guarantee-") and "/guarantees/derivatives/" in target:
            name = href.removeprefix("#guarantee-") + ".md"
            if name == posixpath.basename(target):
                return match[0]
            return match[1] + name + href + match[3]
        if href.startswith(("#", "/")) or ":" in href.split("/", 1)[0]:
            return match[0]
        path, marker, anchor = href.partition("#")
        absolute = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
        if mirror and absolute.startswith("gdd/ledger/"):
            absolute = GENERATED_VIEW_ROOT.as_posix() + absolute[len("gdd/ledger") :]
        relative = posixpath.relpath(absolute, posixpath.dirname(target))
        return match[1] + relative + (marker + anchor if marker else "") + match[3]

    lines = []
    fenced = False
    for line in content.splitlines(keepends=True):
        if line.lstrip().startswith(("```", "~~~")):
            fenced = not fenced
            lines.append(line)
        else:
            lines.append(line if fenced else _LINK.sub(replace, line))
    return "".join(lines)


