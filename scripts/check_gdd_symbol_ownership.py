"""Validate production-module ownership and guarantee traceability.

The committed contract maps each production module to the guarantee ledger
that owns it; the binding is authored and reviewed, never regenerated by this
checker. Current symbols are discovered from the AST at check time: ordinary
helper additions, renames and inlining do not require repinning a name
snapshot. Ledger overrides and critical private symbols remain explicit
and are checked against the live AST. A new production module without a
binding, a binding to a missing ledger, or a governed symbol whose guarantee
does not exist fails this check (``gdd_sync --check`` runs it).
"""

