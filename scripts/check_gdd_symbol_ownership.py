from __future__ import annotations

import ast
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

import yaml


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
CONTRACT_PATH = ROOT / "gdd/ssot/symbol_ownership.yaml"
GUARANTEE_DIR = Path("gdd/ssot/guarantees")
SOURCE_GLOBS = ("jqmc/**/*.py",)
EXCLUDED_FILES = {
    "jqmc/__init__.py",
    "jqmc/_version.py",
}
SYMBOL_KEYS = ("classes", "functions", "async_functions")
REPOSITORY_LIFECYCLES = {"pre-cutover", "cutover"}
LEDGER_LIFECYCLES = {"placeholder", "pre-cutover", "cutover"}
# Ledgers that own no production module (gdd_integrity.yaml holds the GDD
# framework's own guarantees).
AUXILIARY_LEDGERS = frozenset({"gdd/ssot/guarantees/documentation.yaml", "gdd/ssot/guarantees/gdd_integrity.yaml"})


def _module_name(relative: Path) -> str:
    parts = list(relative.with_suffix("").parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def _ledger_for(relative: Path) -> str:
    if relative.parent == Path("jqmc/derivatives"):
        name = "derivatives.yaml"
    else:
        name = f"{relative.stem}.yaml"
    return f"gdd/ssot/guarantees/{name}"


def _empty_symbol_kinds() -> dict[str, list[str]]:
    return {key: [] for key in SYMBOL_KEYS}


def discover_python_ownership(root: Path = ROOT) -> dict[str, dict[str, Any]]:
    """Return public and private top-level symbols grouped by module."""
    paths = set()
    for pattern in SOURCE_GLOBS:
        for path in root.glob(pattern):
            relative = path.relative_to(root)
            if relative.as_posix() not in EXCLUDED_FILES:
                paths.add(path)

    ownership: dict[str, dict[str, Any]] = {}
    for path in sorted(paths):
        relative = path.relative_to(root)
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(relative))
        public = _empty_symbol_kinds()
        private = _empty_symbol_kinds()
        for node in tree.body:
            if not isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            if isinstance(node, ast.ClassDef):
                kind = "classes"
            elif isinstance(node, ast.AsyncFunctionDef):
                kind = "async_functions"
            else:
                kind = "functions"
            visibility = private if node.name.startswith("_") else public
            visibility[kind].append(node.name)

        module = _module_name(relative)
        ownership[module] = {
            "source": relative.as_posix(),
            "ledger": _ledger_for(relative),
            "public_symbols": {key: sorted(values) for key, values in public.items()},
            "private_symbols": {key: sorted(values) for key, values in private.items()},
        }
    return ownership


def _base_contract() -> dict[str, Any]:
    return {
        "schema_version": 1,
        "contract_id": "GDD-SYMBOL-OWNERSHIP-001",
        "lifecycle": "pre-cutover",
        "plain_language": (
            "Every in-scope top-level Python class and function has one primary "
            "ledger; every governed symbol resolves to an existing guarantee."
        ),
        "discovery_policy": {
            "source_globs": list(SOURCE_GLOBS),
            "excluded_paths": {
                "jqmc/__init__.py": "package initializer; no locally defined production symbols",
                "jqmc/_version.py": "generated version metadata",
            },
            "public_name_rule": "a symbol whose name does not start with underscore",
            "private_name_rule": "a symbol whose name starts with underscore",
            "included_symbols": [
                "top-level class definitions",
                "top-level function definitions",
                "top-level async function definitions",
            ],
            "structurally_excluded": [
                "class methods",
                "nested functions and classes",
                "imported symbols and aliases",
                "assignments and constants",
            ],
        },
        "non_python_boundaries": {
            "jqmc_rs": {
                "ledger": "gdd/ssot/guarantees/jqmc_rs.yaml",
                "source_root": "jqmc/rs/src",
                "python_ast_status": "out-of-scope",
                "reason": "Rust symbols require a separate Rust-aware discovery contract",
            }
        },
        "ownership": {},
    }


def _load_yaml_mapping(path: Path, label: str) -> dict[str, Any]:
    from gdd.engine.guarantee_store import is_module_ledger, load_module

    try:
        loaded = load_module(path) if is_module_ledger(path) else yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as exc:
        raise ValueError(f"{label}: invalid YAML: {exc}") from exc
    if not isinstance(loaded, dict):
        raise ValueError(f"{label} must be a YAML mapping")
    return loaded


def _load_contract(path: Path = CONTRACT_PATH) -> dict[str, Any]:
    return _load_yaml_mapping(path, "symbol ownership contract")


def _symbol_names(entry: dict[str, Any], visibility: str) -> set[str]:
    symbols = entry.get(f"{visibility}_symbols", {})
    if not isinstance(symbols, dict):
        return set()
    return {name for key in SYMBOL_KEYS for name in symbols.get(key, []) if isinstance(name, str)}


def _qualified_symbols(module: str, entry: dict[str, Any], visibility: str) -> set[str]:
    return {f"{module}.{name}" for name in _symbol_names(entry, visibility)}


def _ledger_documents(referenced_ledgers: set[str], root: Path, errors: list[str]) -> dict[str, dict[str, Any]]:
    documents: dict[str, dict[str, Any]] = {}
    for ledger in sorted(referenced_ledgers):
        path = root / ledger
        if not path.is_file():
            errors.append(f"missing primary ledger {ledger}")
            continue
        try:
            documents[ledger] = _load_yaml_mapping(path, ledger)
        except ValueError as exc:
            errors.append(str(exc))
    return documents


def _validate_guarantees(
    ledger: str,
    document: dict[str, Any],
    global_guarantee_owners: dict[str, list[str]],
    errors: list[str],
) -> tuple[str | None, set[str]]:
    if not isinstance(document.get("schema_version"), int) or document.get("schema_version") < 1:
        errors.append(f"{ledger}: schema_version must be a positive integer (the ledger schema gate pins the exact value)")
    metadata = document.get("document")
    if not isinstance(metadata, dict):
        errors.append(f"{ledger}: document must be a mapping")
        return None, set()
    lifecycle = metadata.get("lifecycle")
    if lifecycle not in LEDGER_LIFECYCLES:
        errors.append(f"{ledger}: invalid document.lifecycle {lifecycle!r}")
        return None, set()

    guarantees = document.get("guarantees")
    if not isinstance(guarantees, list):
        errors.append(f"{ledger}: guarantees must be a list")
        return lifecycle, set()

    symbol_contract = document.get("symbol_contract")
    if ledger not in AUXILIARY_LEDGERS and not isinstance(symbol_contract, dict):
        errors.append(f"{ledger}: symbol_contract must be a mapping")

    if lifecycle == "placeholder":
        if guarantees:
            errors.append(f"{ledger}: placeholder ledger must not declare guarantees")
        if symbol_contract != {"status": "placeholder"}:
            errors.append(f"{ledger}: placeholder symbol_contract must contain only status: placeholder")
        return lifecycle, set()

    if not guarantees:
        errors.append(f"{ledger}: non-placeholder ledger must declare at least one guarantee")
    guarantee_ids: set[str] = set()
    # The derivative ledger keeps its ordinary-node guarantees in
    # ``module_evidence`` (gdd.engine.ledger.evidence_section); they are
    # guarantees with blocking evidence like any other.
    module_evidence = document.get("module_evidence", [])
    if not isinstance(module_evidence, list):
        errors.append(f"{ledger}: module_evidence must be a list")
        module_evidence = []
    for guarantee in [*guarantees, *module_evidence]:
        if not isinstance(guarantee, dict) or not isinstance(guarantee.get("id"), str):
            errors.append(f"{ledger}: every guarantee must be a mapping with a string id")
            continue
        guarantee_id = guarantee["id"]
        if guarantee_id in guarantee_ids:
            errors.append(f"{ledger}: duplicate guarantee id {guarantee_id}")
        guarantee_ids.add(guarantee_id)
        global_guarantee_owners[guarantee_id].append(ledger)
        evidence = guarantee.get("required_evidence")
        if not isinstance(evidence, (dict, list)) or not evidence:
            errors.append(f"{ledger}: guarantee {guarantee_id} has no blocking required_evidence")

    if ledger not in AUXILIARY_LEDGERS and (
        not isinstance(symbol_contract, dict) or symbol_contract.get("status") != "governed"
    ):
        errors.append(f"{ledger}: non-placeholder symbol_contract must have status: governed")
    return lifecycle, guarantee_ids


def _validate_symbol_bindings(
    ledger: str,
    document: dict[str, Any],
    owned_entries: list[tuple[str, dict[str, Any]]],
    all_guarantee_ids: set[str],
    errors: list[str],
) -> None:
    metadata = document.get("document", {})
    if metadata.get("lifecycle") == "placeholder":
        return
    if ledger in AUXILIARY_LEDGERS:
        return
    symbol_contract = document.get("symbol_contract", {})
    default_refs = symbol_contract.get("default_guarantee_refs")
    overrides = symbol_contract.get("overrides", {})
    critical = symbol_contract.get("critical_private_symbols", [])
    if not isinstance(default_refs, list) or not all(isinstance(ref, str) for ref in default_refs):
        errors.append(f"{ledger}: default_guarantee_refs must be a list of guarantee ids")
        default_refs = []
    if not isinstance(overrides, dict):
        errors.append(f"{ledger}: symbol_contract.overrides must be a mapping")
        overrides = {}
    if not isinstance(critical, list) or not all(isinstance(symbol, str) for symbol in critical):
        errors.append(f"{ledger}: critical_private_symbols must be a list of qualified symbols")
        critical = []

    public_symbols: set[str] = set()
    private_symbols: set[str] = set()
    for module, entry in owned_entries:
        public_symbols.update(_qualified_symbols(module, entry, "public"))
        private_symbols.update(_qualified_symbols(module, entry, "private"))
    owned_symbols = public_symbols | private_symbols

    stale_overrides = sorted(set(overrides) - owned_symbols)
    if stale_overrides:
        errors.append(f"{ledger}: overrides reference unknown symbols {stale_overrides}")
    invalid_critical = sorted(set(critical) - private_symbols)
    if invalid_critical:
        errors.append(f"{ledger}: critical-private entries are not private symbols {invalid_critical}")

    # Ordinary private helpers inherit the default just like public and critical
    # symbols. This provides traceability without demanding a helper-specific test.
    for symbol in sorted(owned_symbols):
        refs = overrides.get(symbol, default_refs)
        if not isinstance(refs, list) or not refs:
            errors.append(f"{ledger}: governed symbol {symbol} has no guarantee_refs")
            continue
        unknown = sorted(ref for ref in refs if ref not in all_guarantee_ids)
        if unknown:
            errors.append(f"{ledger}: symbol {symbol} references unknown guarantees {unknown}")


def validation_errors(contract: dict[str, Any], root: Path = ROOT) -> list[str]:
    errors: list[str] = []
    if contract.get("schema_version") != 1:
        errors.append("schema_version must be 1")
    if contract.get("contract_id") != "GDD-SYMBOL-OWNERSHIP-001":
        errors.append("contract_id must be GDD-SYMBOL-OWNERSHIP-001")
    repository_lifecycle = contract.get("lifecycle")
    if repository_lifecycle not in REPOSITORY_LIFECYCLES:
        errors.append(f"invalid repository lifecycle {repository_lifecycle!r}")
    if contract.get("discovery_policy") != _base_contract()["discovery_policy"]:
        errors.append("discovery_policy no longer matches the checker boundary")
    if contract.get("non_python_boundaries") != _base_contract()["non_python_boundaries"]:
        errors.append("non_python_boundaries no longer matches the checker boundary")

    expected = contract.get("ownership")
    if not isinstance(expected, dict):
        return errors + ["ownership must be a mapping"]
    actual = discover_python_ownership(root)
    missing_modules = sorted(set(actual) - set(expected))
    stale_modules = sorted(set(expected) - set(actual))
    if missing_modules:
        errors.append(f"unowned production modules: {missing_modules}")
    if stale_modules:
        errors.append(f"stale owned modules: {stale_modules}")

    referenced_ledgers: list[str] = []
    entries_by_ledger: dict[str, list[tuple[str, dict[str, Any]]]] = defaultdict(list)
    for module in sorted(set(actual) & set(expected)):
        entry = expected[module]
        # The binding is authored: a ledger may own several modules (for
        # example a module and its persistence helper), but it must be a
        # guarantee ledger and the source must be the live module file.
        if (
            not isinstance(entry, dict)
            or set(entry) != {"source", "ledger"}
            or entry["source"] != actual[module]["source"]
            or not isinstance(entry["ledger"], str)
            or Path(entry["ledger"]).parent != GUARANTEE_DIR
            or Path(entry["ledger"]).suffix != ".yaml"
        ):
            errors.append(f"{module}: ownership entry must bind its live source to a guarantee ledger")
            continue
        referenced_ledgers.append(entry["ledger"])
        entries_by_ledger[entry["ledger"]].append((module, actual[module]))

    rust_ledger = "gdd/ssot/guarantees/jqmc_rs.yaml"
    referenced_ledgers.append(rust_ledger)
    referenced_ledgers.extend(sorted(AUXILIARY_LEDGERS))

    existing_ledgers = {path.relative_to(root).as_posix() for path in (root / GUARANTEE_DIR).glob("*.yaml")}
    referenced_set = set(referenced_ledgers)
    unused_ledgers = sorted(existing_ledgers - referenced_set)
    if unused_ledgers:
        errors.append(f"guarantee ledgers without a production owner: {unused_ledgers}")

    documents = _ledger_documents(referenced_set, root, errors)
    global_guarantee_owners: dict[str, list[str]] = defaultdict(list)
    ledger_lifecycles: dict[str, str | None] = {}
    for ledger, document in documents.items():
        if ledger == rust_ledger:
            expected_document_id = "jqmc_rs"
        elif ledger.endswith("derivatives.yaml"):
            expected_document_id = "jqmc.derivatives"
        else:
            # The ledger named after a module carries that module's id.
            named = [module for module, entry in entries_by_ledger.get(ledger, []) if entry["ledger"] == ledger]
            expected_document_id = named[0] if len(named) == 1 else None
        document_metadata = document.get("document", {})
        actual_document_id = document_metadata.get("id") if isinstance(document_metadata, dict) else None
        if expected_document_id is not None and actual_document_id != expected_document_id:
            errors.append(f"{ledger}: document.id must be {expected_document_id!r}, found {actual_document_id!r}")
        lifecycle, _ = _validate_guarantees(ledger, document, global_guarantee_owners, errors)
        ledger_lifecycles[ledger] = lifecycle

    duplicate_guarantees = {
        guarantee_id: owners for guarantee_id, owners in global_guarantee_owners.items() if len(owners) != 1
    }
    if duplicate_guarantees:
        errors.append(f"guarantee ids must have one authority: {duplicate_guarantees}")
    all_guarantee_ids = set(global_guarantee_owners)

    for ledger, document in documents.items():
        _validate_symbol_bindings(
            ledger,
            document,
            entries_by_ledger.get(ledger, []),
            all_guarantee_ids,
            errors,
        )

    placeholder_ledgers = sorted(ledger for ledger, lifecycle in ledger_lifecycles.items() if lifecycle == "placeholder")
    if repository_lifecycle == "cutover" and placeholder_ledgers:
        errors.append(f"repository cutover requires zero placeholder ledgers; found {placeholder_ledgers}")
    return errors


def main() -> int:
    try:
        contract = _load_contract()
    except (OSError, ValueError) as exc:
        raise SystemExit(f"GDD symbol ownership contract error: {exc}") from exc
    errors = validation_errors(contract)
    if errors:
        raise SystemExit("GDD symbol ownership contract failed:\n- " + "\n- ".join(errors))

    discovered = discover_python_ownership()
    public_count = sum(len(entry["public_symbols"][key]) for entry in discovered.values() for key in SYMBOL_KEYS)
    private_count = sum(len(entry["private_symbols"][key]) for entry in discovered.values() for key in SYMBOL_KEYS)
    ledger_paths = (
        {entry["ledger"] for entry in contract["ownership"].values()} | {"gdd/ssot/guarantees/jqmc_rs.yaml"} | AUXILIARY_LEDGERS
    )
    placeholder_count = sum(
        _load_yaml_mapping(ROOT / ledger, ledger).get("document", {}).get("lifecycle") == "placeholder"
        for ledger in ledger_paths
    )
    print(
        "GDD symbol ownership structure passed "
        f"({len(contract['ownership'])} Python modules, {public_count} public, "
        f"{private_count} private top-level symbols; {placeholder_count} placeholder "
        f"ledgers; repository {contract['lifecycle']})."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
