# =========================================================================== #
# Interacting absolute anchor, native mirror of
# tests/test_jqmc_kernel/test_h4_twist_absolute.py (same fixture, configuration
# and independent reference; see that docstring). The only non-ECP interacting
# twist pattern of this module is h4_twist_j12; li_twist_jdtn, composite_twist_j12
# and pw_twist_j12 carry a Li ccECP whose forward non-local energy is real-projected
# (an open limitation), so they have no admissible independent absolute value yet.
# =========================================================================== #
def _h4_twist_scaled_image_phases(ham, factor):
    """h4_twist_j12 with every pGTO leaf's image phases taken at factor * k (input fault)."""
    geminal = ham.wavefunction_data.geminal_data
    changes = {}
    for name in ("orb_data_up_spin", "orb_data_dn_spin"):
        orb = getattr(geminal, name)
        aos = orb.aos_data
        k = factor * np.asarray(aos.k_point, dtype=float)
        phases = np.exp(2j * np.pi * (np.asarray(aos._image_indices) @ k))
        changes[name] = orb.replace(aos_data=aos.replace(k_point=tuple(k), _image_phase_factors=phases))
    return ham.replace(wavefunction_data=ham.wavefunction_data.replace(geminal_data=geminal.replace(**changes)))


def test_interacting_h4_twist_local_energy_matches_independent_absolute_value_native():
    """Native complex e_L of the interacting H4 twist equals the independent absolute value.

    Same Hamiltonian (H4_pbc_ae_k025_cart.h5, time-reversal SD, J1 + J2, two electrons
    per spin), the same seeded image-offset configuration and the same independent
    reference (explicit Cartesian primitives, integer-image Bloch phases, MO and
    determinant contractions, periodic J1/J2, complex Hessian kinetic energy and a
    NumPy Ewald sum) as the JAX node. ``compute_local_energy_fast_complex`` with a fresh
    geminal inverse must match it, Re and Im together, within the strict zone policy
    of the active mode. The same native call with image phases evaluated at 1.01 k
    (reference unchanged) must fail that comparison.
    """
    from jqmc._precision import get_tolerance_min
    from tests.test_jqmc_kernel.test_h4_twist_absolute import _ZONES
    from tests.test_jqmc_kernel.test_h4_twist_absolute import _case as _h4_absolute_case

    ham, up, down, reference = _h4_absolute_case()
    reference = complex(np.asarray(reference))
    atol, rtol = get_tolerance_min(_ZONES, "strict")
    actual = _eL_native(ham, up, down, _ginv(ham, up, down, True), True)
    assert np.isfinite(actual) and np.isfinite(reference)
    assert abs(reference.imag) > atol + rtol * abs(reference.real), "the anchor must have a live imaginary part"
    assert np.isclose(actual, reference, atol=atol, rtol=rtol, equal_nan=False), (
        f"native e_L={actual!r} vs independent {reference!r}"
    )
    damaged = _h4_twist_scaled_image_phases(ham, 1.01)
    changed = _eL_native(damaged, up, down, _ginv(damaged, up, down, True), True)
    assert np.isfinite(changed)
    assert not np.isclose(changed, reference, atol=atol, rtol=rtol, equal_nan=False), (
        f"1.01 k image phases not detected: {changed!r} vs {reference!r}"
    )


# =========================================================================== #
# Far-cell Bloch phase of native geminal rows (issue #36). An unwrapped MCMC walker
# can drift 1e3 - 1e5 bohr from the home cell. Translating up electron 0 by
# T = n . cell must multiply geminal row 0 by exp(2 pi i k_frac . n) (1 at Gamma)
# and leave every other row unchanged, independently of |n|.
# =========================================================================== #
_FAR_BLOCH_PATTERNS = (
    "pw_twist_jnone",
    "bspline_twist_jnone",
    "pgto_pw_twist_jnone",
    "twist_sphepgto_jnone",
    "pw_gamma_jnone",
    "bspline_gamma_jnone",
)
# Fractional twist of every committed Li_k025 / lithium_k025 fixture (xk = (1/4, 1/4, 1/4)
# in 2 pi / alat units on the cubic cell), restated as the independent expectation.
_FAR_BLOCH_K = np.asarray((0.25, 0.25, 0.25))
_FAR_BLOCH_SHIFTS = ((1, 0, 0), (101, -37, 63), (10001, -7003, 4005), (1000001, -700003, 400005))


@pytest.mark.parametrize("pattern", _FAR_BLOCH_PATTERNS)
def test_far_lattice_translation_geminal_bloch_phase_native(pattern):
    """Native geminal rows obey the Bloch law under far lattice translations.

    Complex PW, complex B-spline, complex pGTO + PW composite and complex sphe-pGTO leaves
    at the Li k = (1/4, 1/4, 1/4) twist (``compute_geminal_complex``) and the real-Gamma PW
    and B-spline leaves (``compute_geminal_all_elements``). Up electron 0 of a seeded
    home-cell configuration is translated by n . cell for n = (1, 0, 0), (101, -37, 63),
    (10001, -7003, 4005) and (1000001, -700003, 400005) (|T| up to about 8e6 bohr; the
    last one makes an error proportional to |r| visible on the real B-spline). Row 0 must equal
    exp(2 pi i k_frac . n) times the unshifted row (the phase is written from the integer
    n and the restated fixture k, 1 at Gamma), the other rows must not change. Each mode
    is judged with its own ao_eval / det_eval strict zone policy relative to max |G|.
    """
    ham = rs_ham(pattern)
    gd = ham.wavefunction_data.geminal_data
    cplx = np.iscomplexobj(np.asarray(gd.orb_data_up_spin.mo_coefficients))
    assert cplx == ("twist" in pattern)
    aos = gd.orb_data_up_spin.aos_data
    k_frac = _FAR_BLOCH_K if cplx else np.zeros(3)
    for leaf in getattr(aos, "children", (aos,)):
        if cplx:
            np.testing.assert_allclose(np.asarray(leaf.k_frac_np), k_frac, atol=ATOL_PYTHON_FP64_LOOSE, rtol=RTOL_BIT_EXACT)
    cell = np.asarray(ham.structure_data.cell, dtype=float)
    rng = np.random.default_rng(3636)
    ru = rng.random((int(gd.num_electron_up), 3)) @ cell
    rd = rng.random((int(gd.num_electron_dn), 3)) @ cell
    g0 = _geminal_matrix(ham, ru, rd, cplx)
    scale = np.max(np.abs(g0))
    assert np.all(np.isfinite(g0)) and scale > 0.0
    atol, rtol = get_tolerance_min(("ao_eval", "det_eval"), "strict")
    failures = []
    for n in _FAR_BLOCH_SHIFTS:
        phase = np.exp(2j * np.pi * float(k_frac @ np.asarray(n)))
        if cplx:
            assert abs(phase - 1.0) > 0.5, f"vacuous shift n={n}"
        ru2 = ru.copy()
        ru2[0] = ru2[0] + np.asarray(n, dtype=float) @ cell
        g1 = _geminal_matrix(ham, ru2, rd, cplx)
        expected = g0.astype(complex)
        expected[0, :] = phase * expected[0, :]
        err = float(np.max(np.abs(g1 - expected)))
        if not err <= atol + rtol * scale:
            failures.append(f"{pattern} n={n}: max|G(r+T) - P G(r)| = {err:.3e} (max|G| = {scale:.3e})")
    assert failures == [], "; ".join(failures)


# =========================================================================== #
# One-image periodic leaf: a periodic pGTO leaf whose build-time image
# truncation keeps only the home image (n_image == 1) is still periodic. The native
# leaf must wrap a translated electron into the home cell (and, at a twist, restore
# the Bloch phase) exactly as for a multi-image leaf; evaluating the raw coordinate
# against the home-only image set returns ~0.
# =========================================================================== #
_ONE_IMAGE_L = 12.0
_ONE_IMAGE_NUCLEUS = np.asarray((6.0, 6.0, 6.0))
_ONE_IMAGE_EXPONENT = 1.0
_ONE_IMAGE_K = np.asarray((0.13, -0.11, 0.2))
_ONE_IMAGE_UP = np.asarray([[6.2, 5.9, 6.3]])
_ONE_IMAGE_DN = np.asarray([[5.85, 6.12, 5.77]])
_ONE_IMAGE_SHIFTS = ((1, -1, 0), (2, 1, 1), (37, -18, 24))
# Brute-force image half-range of the reference sum around the nearest image; every excluded
# image is >= 30 bohr away, where the exponent-1 Gaussian underflows to 0 in fp64.
_ONE_IMAGE_REF_RANGE = 3


def _one_image_reference_orbital(r, k_frac):
    """Independent Bloch sum of one normalized s Gaussian, written from scratch.

    phi_k(r) = sum_n exp(2 pi i k.n) (2 a / pi)^(3/4) exp(-a |r - R - n.cell|^2) over a brute-force
    image box centred on the image nearest to r -- no jqmc image selection, no wrap, no restore phase.
    """
    cell = _ONE_IMAGE_L * np.eye(3)
    centre = np.rint((np.asarray(r, float) - _ONE_IMAGE_NUCLEUS) / _ONE_IMAGE_L).astype(int)
    rng = range(-_ONE_IMAGE_REF_RANGE, _ONE_IMAGE_REF_RANGE + 1)
    total = 0.0j
    for m in ((i, j, k) for i in rng for j in rng for k in rng):
        n = centre + np.asarray(m)
        d = np.asarray(r, float) - _ONE_IMAGE_NUCLEUS - np.asarray(n, float) @ cell
        total += (
            np.exp(2j * np.pi * float(np.dot(k_frac, n)))
            * (2.0 * _ONE_IMAGE_EXPONENT / np.pi) ** 0.75
            * np.exp(-_ONE_IMAGE_EXPONENT * float(d @ d))
        )
    return total


def _one_image_geminal_data(kind: str, twist: bool):
    from jqmc.atomic_orbital import (
        AOs_cart_pgto_data,
        AOs_sphe_pgto_data,
        build_AOs_cart_pgto_complex_data,
        build_AOs_sphe_pgto_complex_data,
    )
    from jqmc.determinant import Geminal_data
    from jqmc.structure import Structure_data

    L = _ONE_IMAGE_L
    structure = Structure_data.build(
        pbc_flag=True,
        positions=_ONE_IMAGE_NUCLEUS[None, :],
        vec_a=(L, 0.0, 0.0),
        vec_b=(0.0, L, 0.0),
        vec_c=(0.0, 0.0, L),
        atomic_numbers=(1,),
        element_symbols=("H",),
        atomic_labels=("H1",),
    )
    common = dict(
        structure_data=structure,
        nucleus_index=(0,),
        num_ao=1,
        num_ao_prim=1,
        orbital_indices=(0,),
        exponents=np.asarray([_ONE_IMAGE_EXPONENT]),
        coefficients=np.asarray([1.0]),
        angular_momentums=(0,),
    )
    angular = (
        dict(polynominal_order_x=(0,), polynominal_order_y=(0,), polynominal_order_z=(0,))
        if kind == "cart"
        else dict(magnetic_quantum_numbers=(0,))
    )
    if twist:
        build = build_AOs_cart_pgto_complex_data if kind == "cart" else build_AOs_sphe_pgto_complex_data
        aos_up = build(**common, **angular, k_point=tuple(float(c) for c in _ONE_IMAGE_K))
        aos_dn = aos_up.with_negated_k()
        lam = np.ones((1, 1), dtype=np.complex128)
    else:
        leaf_cls = AOs_cart_pgto_data if kind == "cart" else AOs_sphe_pgto_data
        aos_up = aos_dn = leaf_cls.build(**common, **angular)
        lam = np.ones((1, 1), dtype=np.float64)
    gd = Geminal_data.build(
        num_electron_up=1, num_electron_dn=1, orb_data_up_spin=aos_up, orb_data_dn_spin=aos_dn, lambda_matrix=lam
    )
    return gd, aos_up


@pytest.mark.parametrize("twist", [True, False], ids=["twist", "gamma"])
@pytest.mark.parametrize("kind", ["sphe", "cart"])
def test_one_image_periodic_leaf_wraps_translated_electron_native(kind, twist):
    """A one-image periodic pGTO leaf obeys the Bloch law for a lattice-translated electron.

    One normalized s Gaussian (exponent 1, coefficient 1) at (6, 6, 6) in the cubic cell 12 I keeps
    exactly one image at build time (asserted), yet is periodic. One up electron at (6.2, 5.9, 6.3) and
    one down electron at (5.85, 6.12, 5.77), unit AGP lambda, down spin at the conjugate twist.
    The native geminal (compute_geminal_complex at k = (0.13, -0.11, 0.2), compute_geminal_all_elements
    at Gamma) of the home configuration and of the configuration with the up electron translated by
    n.cell, n in ``_ONE_IMAGE_SHIFTS``, must equal an independent brute-force Bloch image sum
    phi_k(r_up) phi_-k(r_dn) of the analytic normalized Gaussian, and the translated value must equal
    exp(2 pi i k.n) times the native home value (so |G_translated| == |G_home| != 0). Each mode is judged
    with its own ao_eval / det_eval strict zone policy relative to |G_home|.
    """
    gd, aos_up = _one_image_geminal_data(kind, twist)
    assert int(aos_up._n_image) == 1, f"fixture no longer single-image: n_image={aos_up._n_image}"
    assert bool(aos_up.structure_data.pbc_flag)
    k_frac = _ONE_IMAGE_K if twist else np.zeros(3)
    cell = _ONE_IMAGE_L * np.eye(3)
    native = jqmc_rs.compute_geminal_complex if twist else jqmc_rs.compute_geminal_all_elements
    phi_dn = _one_image_reference_orbital(_ONE_IMAGE_DN[0], -k_frac)
    ref_home = _one_image_reference_orbital(_ONE_IMAGE_UP[0], k_frac) * phi_dn
    g_home = complex(np.asarray(native(gd, _ONE_IMAGE_UP, _ONE_IMAGE_DN))[0, 0])
    scale = abs(ref_home)
    assert np.isfinite(g_home) and scale > 0.0
    atol, rtol = get_tolerance_min(("ao_eval", "det_eval"), "strict")
    failures = []
    if not abs(g_home - ref_home) <= atol + rtol * scale:
        failures.append(f"home: native {g_home!r} vs reference {ref_home!r}")
    for n in _ONE_IMAGE_SHIFTS:
        phase = np.exp(2j * np.pi * float(k_frac @ np.asarray(n)))
        if twist:
            assert abs(phase - 1.0) > 0.5, f"vacuous shift n={n}"
        ru = _ONE_IMAGE_UP + np.asarray(n, dtype=float) @ cell
        ref = _one_image_reference_orbital(ru[0], k_frac) * phi_dn
        g = complex(np.asarray(native(gd, ru, _ONE_IMAGE_DN))[0, 0])
        if not abs(g - ref) <= atol + rtol * scale:
            failures.append(f"n={n}: native {g!r} vs independent image sum {ref!r}")
        if not abs(g - phase * g_home) <= atol + rtol * scale:
            failures.append(f"n={n}: native {g!r} vs exp(2 pi i k.n) G_home {phase * g_home!r}")
        if not abs(abs(g) - abs(g_home)) <= atol + rtol * scale:
            failures.append(f"n={n}: |G_translated| = {abs(g):.6e} vs |G_home| = {abs(g_home):.6e}")
    assert failures == [], f"{kind}/{'twist' if twist else 'gamma'}: " + "; ".join(failures)
