"""Oracle-free periodic invariant tests for the NATIVE Rust kernels (jqmc_rs).

Motivation (rust-integration mission log): four recent periodic far-image bugs --
(1) the J3 orbital evaluated at the RAW electron coordinate instead of its home-cell
image, (2) the DTN Jastrow force using the raw instead of the min-image e-e/e-N
displacement, (3) the J1/J2 kinetic-force metric not following the Jastrow term's
OWN cell (it silently borrowed the geminal's Williamson metric), and (4) the AO
periodic image-tiling truncated for an electron several lattice vectors outside the
home cell -- were all invisible to (i) near-nucleus fixtures, (ii) RIGID all-electron
lattice shifts (a rigid shift of every coordinate together preserves every e-e raw
displacement AND every kernel's home-cell wrap identically, so it degenerately
passes even a broken kernel), and (iii) the lithium fixtures (1 up + 1 dn electron
~5 Bohr apart -> every e-e channel exponentially damped / effectively vacuous).

This module closes that class at unit level with two ORACLE-FREE invariants (native
Rust vs native Rust -- never jax.grad / jqmc's XLA path), each on NON-rigid,
NON-vacuous, far-from-home-cell configs:

  1. single-electron lattice-translation invariance -- translating ONE electron by
     an integer lattice vector, leaving every other electron fixed, must leave
     every physical kernel output (ln|Psi| modulus, the Jastrow part, e_L, the HF
     force, the Pulay force) unchanged. A rigid shift cannot exercise this (every
     kernel wraps a rigid shift away identically); moving exactly one electron
     forces every kernel's OWN periodic image logic to independently get it right.
  2. per-config translation sum rule for atom-centred bases -- Psi and E_L depend on {R_I, r_i} only
     through r_i - R_I - T_n and r_i - r_j, so for ANY config (no MCMC needed):
     sum_I dE_L/dR_I + sum_i dE_L/dr_i == 0 and sum_I dln|Psi|/dR_I +
     sum_i dln|Psi|/dr_i == 0 exactly. This is a from-scratch identity (no
     reference run needed at all) that a wrong per-term metric or a dropped
     image-sum piece generically breaks.

Fixtures: PRIMARY = H4_pbc_ae_{cart,k025_cart}.h5 (2up + 2dn, real-Gamma and a
k=(0.25,0.25,0.25) twist), generated by ``run_pyscf_H4_pbc.py`` -- two
weakly-interacting H2 units in a periodic box, all-electron cc-pVDZ RHF. This is
the ONLY committed periodic fixture with >=2 electrons PER SPIN, so it is the only
source of a natural PARALLEL-spin e-e channel (the DTN f-channel / same-spin
Jastrow-force coverage no lithium or H2_pbc fixture can exercise, since those carry
exactly 1 up + 1 dn). COMPLEMENT = the lithium sphe-ECP J-ladder
(``pbc_gamma_sphepgto_j123`` / ``_jdtn`` / ``twist_sphepgto_jdtn`` /
``twist_sphepgto_j123`` with a phase-free J3 reference from
``_rs_fixtures.rs_ham``) for the ECP + J3 axis H4 (all-electron, no J3 fixture) does
not cover. No committed periodic fixture combines ECP AND >=2 electrons per spin
(that would need e.g. a Si fixture -- ``run_pyscf_Si_pbc_gamma.py`` exists as a
generator template but was not exercised for this suite; left as a documented gap).
The QE lithium PW and pGTO+PW leaves add real-Gamma and complex-twist coverage,
with an active J1/J2 leg in each case. These exercise the composite orbital drift
and pure-PW force paths on the same non-rigid, far-image configurations under
lattice translations. They do not enter the continuous translation sum rule:
at fixed PW coefficients that basis stays in the laboratory frame; translating
the full wavefunction continuously would also require transporting those
coefficients (phase rotation, or rotation of real cos/sin coefficient pairs).

Config recipe (image-offset, NOT a rigid shift, NOT a bare Gaussian scatter): each
electron is anchored near a RANDOMLY CHOSEN NUCLEUS IMAGE (an atom position plus
n*T for n in {0, 2, 5} lattice hops along a randomly chosen lattice vector), then
jittered by a small Gaussian. This keeps |Psi| physically natural (every electron
sits near SOME image of a nucleus, exactly the state a real unwrapped diffusing
walker reaches) while the RAW coordinates land far from the home cell -- this is
what actually manifested the four bugs above (a walker that has diffused several
cells out), unlike a rigid shift or an unanchored far scatter. One OPPOSITE-spin
pair (``dn[0]`` near ``up[0]``) is always forced close (~0.6-1.4 Bohr jitter around
a shared anchor) so the antiparallel J2 / DTN-u channel is non-vacuous by
construction (asserted in ``test_nonvacuous_two_body_sanity``).

Well-conditioning guard: a config whose geminal matrix is numerically close to
singular (near a wavefunction node) is REJECTED and redrawn (see ``_COND_MAX``). A
physical VMC configuration essentially never sits exactly on a node; the near-node
reused-inverse fp floor is a SEPARATE, already-documented regime
(``test_vmc_forces.py::test_vmc_force_reused_inverse_near_node`` /
``test_vmc_pulay_reused_inverse_near_node``), not the periodic-image bug class these
two tests target. Measured: rejection is cheap (<=1 retry typically; see the
``max_tries`` probe in the deliverable report).

Every invariant assertion here compares two NATIVE (jqmc_rs) evaluations against
each other, never against jqmc's JAX/XLA path -- these are unit-level invariants of
the Rust kernels alone, oracle-free by construction. The last node is the exception:
it compares native e_L of a plane-wave determinant
at k != Gamma on a triclinic cell with an independent numpy value (the determinant
kinetic energy, exactly sum_occ |G + k|^2 / 2, evaluated per precision zone,
plus a numpy Ewald sum; still not with XLA).
"""

