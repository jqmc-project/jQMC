@functools.cache
def _pattern_ham(pattern: str):
    if pattern == "h4_j12":
        return _build_ham_generic("H4_pbc_ae_cart.h5", True, None)
    if pattern == "h4_jdtn":
        return _build_ham_generic("H4_pbc_ae_cart.h5", True, {"dtn": True})
    if pattern == "li_j123":
        ham = rs_ham("pbc_gamma_sphepgto_j123")
        return ham.replace(wavefunction_data=_rand_j3(ham.wavefunction_data))
    if pattern == "li_jdtn":
        return rs_ham("pbc_gamma_sphepgto_jdtn")
    if pattern == "h4_twist_j12":
        return _build_ham_generic("H4_pbc_ae_k025_cart.h5", True, None)
    if pattern == "li_twist_jdtn":
        return rs_ham("twist_sphepgto_jdtn")
    if pattern == "li_twist_j123":
        ham = rs_ham("twist_sphepgto_j123")
        return ham.replace(wavefunction_data=_rand_j3(ham.wavefunction_data))
    if pattern == "composite_j12":
        return rs_ham("pbc_composite_j12")
    if pattern == "pw_j12":
        return rs_ham("pw_gamma_j12")
    if pattern == "composite_twist_j12":
        return _build_ham_for_cell("QEPROJ:pgto+pw:Li_k025:ECP", True, None, "SD")
    if pattern == "pw_twist_j12":
        return _build_ham_for_cell("QEPROJ:pw:Li_k025:ECP", True, None, "SD")
    raise KeyError(f"unknown pattern {pattern!r}")


# --------------------------------------------------------------------------- #
# Image-offset config recipe + well-conditioning guard.
# --------------------------------------------------------------------------- #
_N_HOPS = (0, 2, 5)
_HOP_DIRS = ("a1", "a2", "a3")
# geminal condition number above which a config is treated as "on a node" and
# rejected (see the module docstring's well-conditioning-guard paragraph).
_COND_MAX = 1.0e4
_MAX_DRAW_TRIES = 300


def _lattice_vec(ham, direction: str):
    cell = np.asarray(ham.structure_data.cell, float)
    a1, a2, a3 = cell[0], cell[1], cell[2]
    return {"a1": a1, "a2": a2, "a3": a3, "a1+a2-a3": a1 + a2 - a3}[direction]


def _image_offset_anchor(ham, rng, jitter=0.6):
    """One electron's position: near a randomly chosen nucleus IMAGE (an atom plus
    n*T lattice hops, n in ``_N_HOPS``), Gaussian-jittered -- see module docstring.
    """
    R = np.asarray(ham.structure_data.positions, float)
    atom = R[rng.integers(0, len(R))]
    n_i = rng.choice(_N_HOPS)
    direction = _lattice_vec(ham, rng.choice(_HOP_DIRS))
    return atom + n_i * direction + rng.normal(scale=jitter, size=3)


def _draw_cfg(ham, seed: int):
    """Per-electron independent image-offset positions, with a forced OPPOSITE-spin
    close pair (``dn[0]`` near ``up[0]``) for a non-vacuous antiparallel e-e channel.
    """
    gd = ham.wavefunction_data.geminal_data
    nu, nd = int(gd.num_electron_up), int(gd.num_electron_dn)
    rng = np.random.default_rng(seed)
    ru = np.array([_image_offset_anchor(ham, rng) for _ in range(nu)])
    rd = np.array([_image_offset_anchor(ham, rng) for _ in range(nd)])
    rd[0] = ru[0] + rng.normal(scale=0.8, size=3)
    return ru, rd


def _geminal_matrix(ham, ru, rd, cplx: bool):
    gd = ham.wavefunction_data.geminal_data
    if cplx:
        return np.asarray(jqmc_rs.compute_geminal_complex(gd, ru, rd))
    return np.asarray(jqmc_rs.compute_geminal_all_elements(gd, ru, rd))


def _draw_well_conditioned_cfg(ham, seed: int, cplx: bool):
    """``_draw_cfg`` filtered to reject near-node (ill-conditioned geminal) draws."""
    for k in range(_MAX_DRAW_TRIES):
        ru, rd = _draw_cfg(ham, seed * 100_000 + k)
        if np.linalg.cond(_geminal_matrix(ham, ru, rd, cplx)) < _COND_MAX:
            return ru, rd
    raise RuntimeError(f"no well-conditioned config found for seed={seed} after {_MAX_DRAW_TRIES} tries")


def _ginv(ham, ru, rd, cplx: bool):
    G = _geminal_matrix(ham, ru, rd, cplx)
    ginv = np.linalg.inv(G)
    return ginv.astype(np.complex128) if cplx else ginv


# --------------------------------------------------------------------------- #
# Native aggregate evaluators (e_L, ln|Psi|, HF force, Pulay force).
# --------------------------------------------------------------------------- #
def _eL_native(ham, ru, rd, ginv, cplx: bool):
    if cplx:
        re, im = jqmc_rs.compute_local_energy_fast_complex(ham, ru, rd, _W, _GP, ginv)
        return complex(re, im)
    return jqmc_rs.compute_local_energy_fast(ham, ru, rd, _W, _GP, ginv)


def _ln_psi_native(ham, ru, rd, cplx: bool):
    """ln|Psi| = ln|det G| + J1 + J2 + DTN, assembled from native VALUE calls (each
    independently periodicity-correct -- see the probe measurements in the module's
    companion report). Returns ``None`` if the ham carries an active J3 (no native
    call exposes a periodicity-correct J3 VALUE; the J3 grad/lap piece is still
    covered, both here indirectly through e_L/HF/Pulay and directly through
    ``compute_grads_and_laplacian_jastrow_part`` in the translation-invariance test).
    """
    wf = ham.wavefunction_data
    jas = wf.jastrow_data
    if jas.jastrow_three_body_data is not None:
        return None
    gem = wf.geminal_data
    ln_det = jqmc_rs.compute_ln_det_complex(gem, ru, rd) if cplx else jqmc_rs.compute_ln_det_geminal_all_elements(gem, ru, rd)
    v = float(np.real(ln_det))
    if jas.jastrow_one_body_data is not None:
        v += float(jqmc_rs.compute_Jastrow_one_body(jas.jastrow_one_body_data, ru, rd))
    if jas.jastrow_two_body_data is not None:
        v += float(jqmc_rs.compute_Jastrow_two_body(jas.jastrow_two_body_data, ru, rd))
    if jas.jastrow_dtn_data is not None:
        v += float(jqmc_rs.compute_dtn_value(jas.jastrow_dtn_data, ru, rd))
    return v


def _hf_and_pulay_force(ham, ru, rd, ginv, cplx: bool):
    wf = ham.wavefunction_data
    gem, jas, cp = wf.geminal_data, wf.jastrow_data, ham.coulomb_potential_data
    if cplx:
        hf = jqmc_rs.vmc_grad_e_L_pbc_complex(gem, jas, cp, ru, rd, _W, _GP, None)
        pulay = jqmc_rs.vmc_grad_ln_psi_pbc_complex(gem, jas, ru, rd)
    else:
        hf = jqmc_rs.vmc_grad_e_L_pbc(gem, jas, cp, ru, rd, _W, _GP, ginv)
        pulay = jqmc_rs.vmc_grad_ln_psi_pbc(gem, jas, ru, rd, ginv)
    hf = tuple(np.asarray(x) for x in hf)
    pulay = tuple(np.asarray(x) for x in pulay)
    return hf, pulay


# =========================================================================== #
# Sanity: the forced-close e-e pair is genuinely non-vacuous (guards against the
# lithium-fixture failure mode -- a "close pair" that is not actually close enough
# to make the Jastrow coupling live would make every invariant below trivially
# true, defeating the point of this suite).
# =========================================================================== #
@pytest.mark.parametrize("pattern", _LATTICE_PATTERNS)
def test_nonvacuous_two_body_sanity(pattern):
    """Nonvacuous two body sanity."""
    ham = _pattern_ham(pattern)
    cplx = pattern in _CPLX_PATTERNS
    ru, rd = _draw_well_conditioned_cfg(ham, 0, cplx)
    j2_data = ham.wavefunction_data.jastrow_data.jastrow_two_body_data
    assert j2_data is not None, f"{pattern}: no two-body Jastrow -- non-vacuousness is not checkable"
    j2 = abs(float(jqmc_rs.compute_Jastrow_two_body(j2_data, ru, rd)))
    assert j2 > RS_PERIODIC_INVARIANCE_MIN_JASTROW_TWO_BODY, (
        f"{pattern}: forced close e-e pair is vacuous (|J2|={j2:.4g}); config recipe regressed"
    )


# =========================================================================== #
# Test 1: single-electron lattice-translation invariance.
# =========================================================================== #
_SHIFT_N = (1, 3, 6)
_SHIFT_DIRS = ("a1", "a2", "a1+a2-a3")
_SHIFT_ELECS = (("up", 0), ("dn", 0))


@pytest.mark.parametrize("elec", _SHIFT_ELECS, ids=["up0", "dn0"])
@pytest.mark.parametrize("direction", _SHIFT_DIRS)
@pytest.mark.parametrize("n", _SHIFT_N)
@pytest.mark.parametrize("pattern", _LATTICE_PATTERNS)
def test_single_electron_lattice_translation_invariance(pattern, n, direction, elec):
    """Single electron lattice translation invariance."""
    ham = _pattern_ham(pattern)
    cplx = pattern in _CPLX_PATTERNS
    ru, rd = _draw_well_conditioned_cfg(ham, 0, cplx)
    if pattern in _PW_PATTERNS:
        # A broken composite can lose the entire GTO derivative block at BOTH
        # far-image endpoints and still pass a far-to-far comparison. Start
        # these new leaf rows in the home cell before moving just one electron.
        # Keep every original atom-centred row's independent-image recipe.
        cell = np.asarray(ham.structure_data.cell, dtype=float)
        inv_cell = np.linalg.inv(cell)
        ru = ru - np.floor(ru @ inv_cell) @ cell
        rd = rd - np.floor(rd @ inv_cell) @ cell
    G = _geminal_matrix(ham, ru, rd, cplx)  # every case: cond(G) of the realized (possibly wrapped) base point
    cond_G = np.linalg.cond(G)
    assert cond_G < _COND_MAX

    T = n * _lattice_vec(ham, direction)
    ru2, rd2 = ru.copy(), rd.copy()
    if elec[0] == "up":
        ru2[elec[1]] = ru2[elec[1]] + T
    else:
        rd2[elec[1]] = rd2[elec[1]] + T

    ginv1 = _ginv(ham, ru, rd, cplx)
    ginv2 = _ginv(ham, ru2, rd2, cplx)

    # e_L (compute_local_energy_fast[_complex]): the full aggregate local energy,
    # exercising the AO/kinetic/ECP-mesh far-image logic all four bugs lived in.
    eL1 = _eL_native(ham, ru, rd, ginv1, cplx)
    eL2 = _eL_native(ham, ru2, rd2, ginv2, cplx)
    np.testing.assert_allclose(eL2, eL1, atol=_ATOL_INVARIANT, rtol=_RTOL_INVARIANT, err_msg=f"{pattern} e_L")

    # ln|Psi| = ln|det| + J1 + J2 + DTN (skipped when an active J3 makes this
    # unassemblable from native VALUE calls -- see ``_ln_psi_native``).
    lp1 = _ln_psi_native(ham, ru, rd, cplx)
    lp2 = _ln_psi_native(ham, ru2, rd2, cplx)
    if lp1 is not None:
        np.testing.assert_allclose(lp2, lp1, atol=_ATOL_INVARIANT, rtol=_RTOL_INVARIANT, err_msg=f"{pattern} ln|Psi|")

    # Jastrow part (grad + laplacian of J1+J2+J3+DTN together, whichever are
    # active): covers J3 too (unlike the ln|Psi| value check above).
    jas = ham.wavefunction_data.jastrow_data
    jg1 = jqmc_rs.compute_grads_and_laplacian_jastrow_part(jas, ru, rd)
    jg2 = jqmc_rs.compute_grads_and_laplacian_jastrow_part(jas, ru2, rd2)
    for a, b in zip(jg1, jg2):
        np.testing.assert_allclose(
            np.asarray(b),
            np.asarray(a),
            atol=_ATOL_INVARIANT,
            rtol=_RTOL_INVARIANT,
            err_msg=f"{pattern} Jastrow part",
        )

    # HF force (vmc_grad_e_L_pbc[_complex]) and Pulay force (vmc_grad_ln_psi_pbc[_complex]).
    (hfR1, hfu1, hfd1), (puR1, puu1, pud1) = _hf_and_pulay_force(ham, ru, rd, ginv1, cplx)
    (hfR2, hfu2, hfd2), (puR2, puu2, pud2) = _hf_and_pulay_force(ham, ru2, rd2, ginv2, cplx)
    for a, b, tag in ((hfR1, hfR2, "dR"), (hfu1, hfu2, "dr_up"), (hfd1, hfd2, "dr_dn")):
        np.testing.assert_allclose(b, a, atol=_ATOL_INVARIANT, rtol=_RTOL_INVARIANT, err_msg=f"{pattern} HF force {tag}")
    for a, b, tag in ((puR1, puR2, "dR"), (puu1, puu2, "dr_up"), (pud1, pud2, "dr_dn")):
        np.testing.assert_allclose(
            b,
            a,
            atol=_ATOL_INVARIANT,
            rtol=_RTOL_INVARIANT,
            err_msg=f"{pattern} Pulay force {tag}",
        )


# =========================================================================== #
# Test 2: per-config translation sum rule (no shift, no MCMC -- a from-scratch
# identity on any single config). Both the HF and Pulay sums use the unified
# ``ATOL_FLOOR_MEDIUM`` / ``RTOL_FLOOR_MEDIUM``. The dR force channel and the dr drift
# share the cart-leaf full-image ``pgto_deriv`` (not a batch/sphe LEPSBAS-cutoff AO
# grad), so both close at the fp64 cancellation floor: measured max |sum| Pulay
# <= 2.1e-13, HF <= 1.6e-13 across the H4-pbc (real-Gamma + k=0.25 twist) and lithium
# sphe-ECP J3/DTN ladder, well inside the floor (a LEPSBAS-cutoff AO grad gives Pulay
# ~1.07e-8 / HF ~4.93e-8).
# =========================================================================== #
_SUM_RULE_SEEDS = (0, 1, 2)


@pytest.mark.parametrize("seed", _SUM_RULE_SEEDS)
@pytest.mark.parametrize("pattern", _ALL_PATTERNS)
def test_per_config_translation_sum_rule(pattern, seed):
    """Per config translation sum rule."""
    ham = _pattern_ham(pattern)
    cplx = pattern in _CPLX_PATTERNS
    ru, rd = _draw_well_conditioned_cfg(ham, seed, cplx)
    ginv = _ginv(ham, ru, rd, cplx)

    (hfR, hfu, hfd), (puR, puu, pud) = _hf_and_pulay_force(ham, ru, rd, ginv, cplx)

    hf_sum = np.real(hfR).sum(axis=0) + np.real(hfu).sum(axis=0) + np.real(hfd).sum(axis=0)
    np.testing.assert_allclose(
        hf_sum,
        np.zeros(3),
        atol=_ATOL_INVARIANT,
        rtol=_RTOL_INVARIANT,
        err_msg=f"{pattern} seed={seed}: sum_I dE_L/dR_I + sum_i dE_L/dr_i != 0",
    )

    pulay_sum = np.real(puR).sum(axis=0) + np.real(puu).sum(axis=0) + np.real(pud).sum(axis=0)
    np.testing.assert_allclose(
        pulay_sum,
        np.zeros(3),
        atol=_ATOL_INVARIANT,
        rtol=_RTOL_INVARIANT,
        err_msg=f"{pattern} seed={seed}: sum_I dln|Psi|/dR_I + sum_i dln|Psi|/dr_i != 0",
    )


# The per-config translation sum rule at the fp64 CANCELLATION FLOOR. The
# unified ``ATOL_FLOOR_MEDIUM`` (2e-5) is the native-vs-JAX force PARITY floor -- it deliberately does
# NOT resolve the (since fixed) dR-vs-dr IMAGE-SET asymmetry: the dr DRIFT channel
# (``pbc_drift`` -> ``det_grad_field`` / batch J3 drift) applied the dynamic LEPSBAS per-image
# cutoff while the dR channel evaluates AO gradients on the FULL static image tiling. Per image
# ``dAO/dR = -dAO/dr`` EXACTLY, so a MATCHED image set closes this identity at the fp64 floor
# (measured <= 2.1e-13 across these patterns/seeds) and a MISMATCHED one only at ~1e-8
# (Gaussian-curvature-amplified) -- under 2e-5, so the loosened row above cannot see it. This
# In full precision the same-native identity uses the strict crossed-zone
# tolerance. In mixed precision these HF and
# Pulay sums cancel fp32 summands below one ulp of their size, so the mixed lane
# keeps the medium envelope.
# Reverting
# ``pbc_drift`` + ``grad_j3_wrt_r_e_pbc`` to the batch drift breaks it (li_j123 HF ~7.7e-8,
# h4/li Pulay ~7e-9..1.1e-8 in full precision).


@pytest.mark.parametrize("seed", _SUM_RULE_SEEDS)
@pytest.mark.parametrize("pattern", _REAL_PATTERNS)
def test_per_config_translation_sum_rule_fp_floor(pattern, seed):
    """Per config translation sum rule fp floor."""
    ham = _pattern_ham(pattern)
    ru, rd = _draw_well_conditioned_cfg(ham, seed, False)
    ginv = _ginv(ham, ru, rd, False)
    (hfR, hfu, hfd), (puR, puu, pud) = _hf_and_pulay_force(ham, ru, rd, ginv, False)
    hf_sum = np.real(hfR).sum(axis=0) + np.real(hfu).sum(axis=0) + np.real(hfd).sum(axis=0)
    pulay_sum = np.real(puR).sum(axis=0) + np.real(puu).sum(axis=0) + np.real(pud).sum(axis=0)
    if is_mixed_precision_enabled():
        atol, rtol = get_tolerance_xla_rust_consistency(("ao_eval", "ao_grad_lap", "det_grad_lap"), level="medium")
    else:
        atol, rtol = get_tolerance_min(("ao_eval", "ao_grad_lap", "det_grad_lap"), level="strict")
    np.testing.assert_allclose(
        hf_sum,
        np.zeros(3),
        atol=atol,
        rtol=rtol,
        err_msg=f"{pattern} seed={seed}: HF sum-rule above fp64 floor (dR/dr image-set asymmetry)",
    )
    np.testing.assert_allclose(
        pulay_sum,
        np.zeros(3),
        atol=atol,
        rtol=rtol,
        err_msg=f"{pattern} seed={seed}: Pulay sum-rule above fp64 floor (dR/dr image-set asymmetry)",
    )


