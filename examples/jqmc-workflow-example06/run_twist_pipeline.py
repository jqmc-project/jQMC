from __future__ import annotations

import os

import h5py

from jqmc_workflow import (
    Container,
    FileFrom,
    Launcher,
    MCMC_Workflow,
    QE_Workflow,
    ValueFrom,
    VMC_Workflow,
)

# -- Configuration -------------------------------------------------
# docs: configuration-begin
SERVER = "cluster"  # machine name in jqmc_setting_local/ or ~/.jqmc_setting/
QUEUE_LABEL = "cores-128-mpi-128-omp-1-3h"  # MPI ranks must be a multiple of N_TWIST
N_TWIST = 8

NUMBER_OF_WALKERS = 8  # walkers per MPI rank
NUM_OPT_STEPS = 30  # VMC optimization steps
NUM_VMC_MCMC_STEPS = 150  # MCMC measurements per optimization step
WF_DUMP_FREQ = 1  # dump every step: VMC_Workflow hands on the average of the last 20 steps
NUM_MCMC_STEPS = 10000  # measurements of the downstream MCMC run
DT = 2.0  # MCMC step size (bohr)
PRECISION_MODE = "mixed"  # "full" (default, reference) or "mixed"
# docs: configuration-end


def build_workflows(base_dir: str) -> tuple[list[Container], Container]:
    """Build the conversion, optimization, and downstream sampling DAG."""
    # docs: workflows-begin
    qe_save_dir = os.path.abspath(os.path.join(base_dir, "..", "jqmc-example09", "01DFT", "out", "silicon_twist.save"))

    conversion = Container(
        label="qe",
        dirname="01_qe_to_jqmc",
        workflow=QE_Workflow(
            qe_save_dir=qe_save_dir,
            kind="bspline",
            twist_average=True,
            hamiltonian_file="hamiltonian_data.h5",
            j2_parameter=1.0,
            verbosity="high",
        ),
    )

    vmc = Container(
        label="vmc",
        dirname="02_vmc",
        input_files=[FileFrom("qe", "hamiltonian_data.h5")],
        workflow=VMC_Workflow(
            server_machine_name=SERVER,
            queue_label=QUEUE_LABEL,
            jobname="si-twist-vmc",
            number_of_walkers=NUMBER_OF_WALKERS,
            num_opt_steps=NUM_OPT_STEPS,
            num_mcmc_steps=NUM_VMC_MCMC_STEPS,
            # Code minimums: 30 warmup measurements and 10 bins.
            num_mcmc_warmup_steps=30,
            num_mcmc_bin_blocks=10,
            Dt=DT,
            wf_dump_freq=WF_DUMP_FREQ,
            opt_J1_param=False,
            opt_J2_param=True,
            opt_J3_param=False,
            opt_geminal=True,
            optimizer_kwargs={
                "method": "sr",
                "delta": 0.1,
                "epsilon": 0.001,
                "use_lm": True,
            },
            precision_mode=PRECISION_MODE,
            verbosity="high",
        ),
    )

    mcmc = Container(
        label="mcmc",
        dirname="03_mcmc",
        input_files=[
            FileFrom("vmc", ValueFrom("vmc", "optimized_hamiltonian")),
        ],
        rename_input_files=["hamiltonian_data.h5"],
        workflow=MCMC_Workflow(
            server_machine_name=SERVER,
            queue_label=QUEUE_LABEL,
            jobname="si-twist-mcmc",
            number_of_walkers=NUMBER_OF_WALKERS,
            num_mcmc_steps=NUM_MCMC_STEPS,
            num_mcmc_warmup_steps=30,
            num_mcmc_bin_blocks=10,
            Dt=DT,
            precision_mode=PRECISION_MODE,
            verbosity="high",
        ),
    )
    # docs: workflows-end
    return [conversion, vmc, mcmc], vmc


if __name__ == "__main__":
    example_dir = os.path.dirname(os.path.abspath(__file__))
    os.chdir(example_dir)
    workflows, vmc_container = build_workflows(example_dir)
    Launcher(workflows=workflows, draw_graph=True).launch()

    published = vmc_container.output_values.get("optimized_hamiltonian")
    if published is None:
        raise RuntimeError("The VMC stage published no optimized Hamiltonian.")
    # The published file must be a multi-twist Hamiltonian (``_meta``,
    # ``shared`` and ``twists`` groups) holding every twist. Read its header
    # directly instead of trusting the filename.
    with h5py.File(os.path.join(example_dir, "02_vmc", published), "r") as h5:
        is_multi_twist = all(name in h5 for name in ("_meta", "shared", "twists"))
        n_twist_published = int(h5["_meta"].attrs.get("n_twist", 0)) if is_multi_twist else 0
    if not is_multi_twist:
        raise RuntimeError(f"Expected a multi-twist Hamiltonian, got {published!r}.")
    if n_twist_published != N_TWIST:
        raise RuntimeError(f"{published!r} holds {n_twist_published} twists, expected {N_TWIST}.")
    print(f"Published optimized {N_TWIST}-twist Hamiltonian: {published}")

    # Twist-averaged MCMC energy, computed by the workflow with
    # ``jqmc-tool mcmc compute-energy 03_mcmc/restart.h5 -w 30 -b 10``.
    mcmc_values = workflows[-1].output_values or {}
    energy = mcmc_values.get("energy")
    energy_error = mcmc_values.get("energy_error")
    if energy is not None:
        print(f"Twist-averaged MCMC energy: {energy} +- {energy_error} Ha")
    else:
        print("The MCMC stage published no energy; inspect 03_mcmc/ logs.")
